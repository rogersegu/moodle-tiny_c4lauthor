/**
 * Build the standalone fallback: dist/standalone.css and dist/standalone.js.
 *
 * The admin page "Standalone fallback" offers them for Additional HTML, so content keeps
 * working after the plugin is uninstalled.
 *
 * - CSS: scss/standalone.scss (content styles only), compressed, with every
 *   [[pix:tiny_c4lauthor|name]] inlined as an SVG data URI.
 * - JS: amd/src/runtime.js bundled without Moodle's modules; core/str is replaced by
 *   tools/standalone/str.js.
 *
 * Run from the plugin directory: node tools/build-standalone.mjs
 *
 * @copyright   2026 bdecent gmbh <https://bdecent.de>
 * @license     http://www.gnu.org/copyleft/gpl.html GNU GPL v3 or later
 */

import {execFileSync} from 'node:child_process';
import {existsSync, mkdirSync, readFileSync, writeFileSync} from 'node:fs';
import {dirname, join, resolve} from 'node:path';
import {fileURLToPath} from 'node:url';

const SASS = 'sass@1.91.0';
const ESBUILD = 'esbuild@0.25.10';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const dist = join(root, 'dist');
if (!existsSync(dist)) {
    mkdirSync(dist);
}
const npx = (args) => execFileSync('npx', ['--yes', ...args], {cwd: root, encoding: 'utf8'});

// An SVG as a data URI, URL-encoded rather than base64, which keeps it smaller.
const svgDataUri = (name) => {
    const file = join(root, 'pix', name + '.svg');
    if (!existsSync(file)) {
        throw new Error('pix file not found: ' + name);
    }
    const svg = readFileSync(file, 'utf8').replace(/\s+/g, ' ').replace(/> </g, '><').trim().replace(/"/g, "'");
    return 'url("data:image/svg+xml,' + encodeURIComponent(svg).replace(/%20/g, ' ').replace(/%27/g, "'")
        .replace(/%3D/g, '=').replace(/%3A/g, ':').replace(/%2F/g, '/') + '")';
};

const header = '/* C4L Author standalone fallback. Generated by tools/build-standalone.mjs; do not edit. */\n';

// Each icon is defined once as a custom property, as masks name it twice (with -webkit-).
const icons = new Map();
const rules = npx([SASS, '--no-source-map', '--style=compressed', '--quiet', 'scss/standalone.scss'])
    .replace(/url\(\[\[pix:tiny_c4lauthor\|([^\]]+)\]\]\)/g, (match, name) => {
        if (!icons.has(name)) {
            icons.set(name, `--c4l-icon-${icons.size + 1}`);
        }
        return `var(${icons.get(name)})`;
    });
const iconRule = ':root{' + Array.from(icons, ([name, property]) => `${property}:${svgDataUri(name.trim())}`).join(';') + '}';
const css = iconRule + rules.trim();
writeFileSync(join(dist, 'standalone.css'), header + css + '\n');

const js = npx([ESBUILD, 'amd/src/runtime.js', '--bundle', '--format=iife', '--minify', '--target=es2020', '--tsconfig-raw={}',
    '--alias:core/str=./tools/standalone/str.js', '--legal-comments=none',
    '--footer:js=document.readyState==="loading"?document.addEventListener("DOMContentLoaded",C4LAuthorRuntime.init):'
        + 'C4LAuthorRuntime.init();',
    '--global-name=C4LAuthorRuntime']);
writeFileSync(join(dist, 'standalone.js'), header + js.trim() + '\n');

console.log(`dist/standalone.css: ${css.length} bytes, dist/standalone.js: ${js.length} bytes`);
